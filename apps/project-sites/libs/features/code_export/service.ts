// ─── Main generator ─────────────────────────────────────────────────────────

/**
 * Generates a complete, deployable Cloudflare Worker project from site bindings.
 *
 * The returned manifest contains every file needed to run the site as a
 * standalone Worker — just unzip, `npm install`, and `npx wrangler deploy`.
 *
 * @param bindings - Site configuration including slug, pages, assets, and CF resource IDs.
 * @returns A typed manifest with all generated project files.
 *
 * @example
 * ```ts
 * const project = generateCfProject({
 *   slug: 'my-bakery',
 *   d1DatabaseName: 'my-bakery-db',
 *   r2BucketName: 'my-bakery-assets',
 *   pages: [{ path: '/', title: 'Home', content: '<h1>Welcome</h1>' }],
 * });
 * // Use project.files to build a zip download.
 * ```
 */
export function generateCfProject(bindings: SiteBindings): CfProjectManifest {
  // Defensive defaults — callers may pass plain objects without Zod defaults.
  const b = {
    ...bindings,
    pages: bindings.pages ?? [],
    staticAssets: bindings.staticAssets ?? [],
    d1Schema: bindings.d1Schema ?? [],
    d1Data: bindings.d1Data ?? [],
  };

  const files: GeneratedFile[] = [];
  const push = (path: string, content: string) => {
    files.push({
      path,
      content,
      sizeBytes: new TextEncoder().encode(content).length,
    });
  };

  // Core config files
  push('wrangler.toml', generateWranglerToml(bindings));
  push('package.json', generatePackageJson(bindings));
  push('tsconfig.json', generateTsconfig());
  push('README.md', generateReadme(bindings));

  // Worker source
  push('src/index.ts', generateWorkerIndex(bindings));

  // D1 migrations
  if (b.d1Schema.length > 0) {
    push(
      'migrations/0001_schema.sql',
      [
        '-- Generated by ProjectSites.dev Code Export',
        `-- Site: ${bindings.slug}`,
        '',
        ...b.d1Schema,
      ].join('\n'),
    );
  }

  if (b.d1Data.length > 0) {
    push(
      'migrations/0002_seed.sql',
      [
        '-- Generated by ProjectSites.dev Code Export',
        `-- Site: ${bindings.slug}`,
        '-- ⚠️ Review before applying — contains your site data.',
        '',
        ...b.d1Data,
      ].join('\n'),
    );
  }

  // Static assets
  for (const asset of b.staticAssets) {
    push(`public/${asset.path}`, asset.content);
  }

  // Upload helper script
  push(
    'scripts/upload-assets.sh',
    [
      '#!/usr/bin/env bash',
      '# Upload static assets to R2',
      '# Generated by ProjectSites.dev Code Export',
      `set -euo pipefail`,
      '',
      `BUCKET="${bindings.r2BucketName || '<your-bucket>'}"`,
      '',
      'echo "Uploading static assets to R2 bucket: $BUCKET"',
      'for file in public/*; do',
      '  key="${file#public/}"',
      '  echo "  $key"',
      '  npx wrangler r2 object put "$BUCKET/$key" --file "$file"',
      'done',
      '',
      'echo "Done. Assets live at https://<your-worker>.<subdomain>.workers.dev/assets/<key>"',
    ].join('\n'),
  );

  const totalSize = files.reduce((sum, f) => sum + f.sizeBytes, 0);

  return {
    projectName: `${bindings.slug}${WORKER_NAME_SUFFIX}`,
    generatedAt: new Date().toISOString(),
    files,
    totalSize,
    fileCount: files.length,
    d1Binding: 'DB',
    r2Binding: 'ASSETS',
  };
}
